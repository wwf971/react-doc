// Restricted modes of nested Markdown. Both plugins change structure only;
// link meaning stays with remark-doc-link.js.

// remarkNodeTypeRestrict({ nodeTypeAllowedList }):
// a node whose type is not allowed is degraded in place:
//   has children -> replaced by its children   ([a](b.md) -> a)
//   has a value  -> replaced by plain text     (`code`   -> code)
//   otherwise    -> removed
// run it before remarkDocLink, so a disallowed 'link' never becomes a DocLink.
export function remarkNodeTypeRestrict(options = {}) {
  const typeAllowedSet = new Set(options.nodeTypeAllowedList ?? []);
  return (tree) => {
    if (typeAllowedSet.size === 0) return;
    childrenReplace(tree, (node) => {
      if (typeAllowedSet.has(node.type)) return undefined;
      if (Array.isArray(node.children)) return node.children;
      if (typeof node.value === 'string') return [{ type: 'text', value: node.value }];
      return [];
    });
  };
}

// remarkContentSanitize(): for text-focused or untrusted content.
//   removed:   ESM, expressions, raw html
//   unwrapped: authored JSX elements; their Markdown children stay
//   kept:      elements generated by remarkDocLink (node.data.isDocLinkGenerated),
//              which an authored element of the same name does not have
// run it after remarkDocLink.
const NODE_TYPE_REMOVED_SET = new Set(['mdxjsEsm', 'mdxFlowExpression', 'mdxTextExpression', 'html']);
const NODE_TYPE_JSX_SET = new Set(['mdxJsxFlowElement', 'mdxJsxTextElement']);

export function remarkContentSanitize() {
  return (tree) => {
    childrenReplace(tree, (node) => {
      if (NODE_TYPE_REMOVED_SET.has(node.type)) return [];
      if (!NODE_TYPE_JSX_SET.has(node.type)) return undefined;
      if (node.data?.isDocLinkGenerated === true) return undefined;
      return node.children ?? [];
    });
  };
}

// remarkInlineUnwrap(): content mode 'inline' of text input. content that is
// one paragraph renders as its phrasing children, without the <p>; any other
// content keeps its block structure.
export function remarkInlineUnwrap() {
  return (tree) => {
    if (tree.children?.length !== 1 || tree.children[0].type !== 'paragraph') return;
    tree.children = tree.children[0].children;
  };
}

// nodeReplace(node) returns undefined to keep the node, or the node list that
// takes its place. replacement nodes are checked again, so nested unwrapping
// works at any depth.
function childrenReplace(parent, nodeReplace) {
  if (!Array.isArray(parent?.children)) return;
  const childList = [];
  const queue = [...parent.children];
  while (queue.length > 0) {
    const node = queue.shift();
    const nodeListReplacement = nodeReplace(node);
    if (nodeListReplacement === undefined) {
      childrenReplace(node, nodeReplace);
      childList.push(node);
    } else {
      queue.unshift(...nodeListReplacement);
    }
  }
  parent.children = childList;
}
